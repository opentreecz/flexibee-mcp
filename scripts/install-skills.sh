#!/usr/bin/env bash
# install-skills.sh — install FlexiBee MCP skills to all supported AI client locations.
#
# Usage:
#   bash scripts/install-skills.sh           # install to all locations (default)
#   bash scripts/install-skills.sh --all     # same as default
#   bash scripts/install-skills.sh --opencode
#   bash scripts/install-skills.sh --claude
#   bash scripts/install-skills.sh --agents
#   bash scripts/install-skills.sh --codex   # updates ~/.codex/AGENTS.md
#   bash scripts/install-skills.sh --dry-run # print targets without writing
#
# Skill discovery paths by client:
#   OpenCode : ~/.config/opencode/skills/<name>/SKILL.md
#   Claude Code: ~/.claude/skills/<name>/SKILL.md
#   Agent Skills (OpenCode, Claude Code, Antigravity, ...):
#              ~/.agents/skills/<name>/SKILL.md
#   Codex CLI: ~/.codex/AGENTS.md (appends skill content)

set -euo pipefail

# ── Resolve repository root ──────────────────────────────────────────────────

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
SKILLS_DIR="$REPO_ROOT/skills"

if [[ ! -d "$SKILLS_DIR" ]]; then
  echo "ERROR: skills/ directory not found at $SKILLS_DIR" >&2
  exit 1
fi

# ── Parse arguments ───────────────────────────────────────────────────────────

TARGET_OPENCODE=false
TARGET_CLAUDE=false
TARGET_AGENTS=false
TARGET_CODEX=false
DRY_RUN=false

parse_args() {
  if [[ $# -eq 0 ]] || [[ "$1" == "--all" ]]; then
    TARGET_OPENCODE=true
    TARGET_CLAUDE=true
    TARGET_AGENTS=true
    TARGET_CODEX=true
    return
  fi
  for arg in "$@"; do
    case "$arg" in
      --opencode) TARGET_OPENCODE=true ;;
      --claude)   TARGET_CLAUDE=true   ;;
      --agents)   TARGET_AGENTS=true   ;;
      --codex)    TARGET_CODEX=true    ;;
      --dry-run)  DRY_RUN=true         ;;
      --all)
        TARGET_OPENCODE=true
        TARGET_CLAUDE=true
        TARGET_AGENTS=true
        TARGET_CODEX=true
        ;;
      *)
        echo "Unknown argument: $arg" >&2
        echo "Usage: $0 [--all|--opencode|--claude|--agents|--codex] [--dry-run]" >&2
        exit 1
        ;;
    esac
  done
  # If only --dry-run was passed with no target, default to all
  if [[ "$TARGET_OPENCODE" == "false" && "$TARGET_CLAUDE" == "false" && \
        "$TARGET_AGENTS" == "false" && "$TARGET_CODEX" == "false" ]]; then
    TARGET_OPENCODE=true
    TARGET_CLAUDE=true
    TARGET_AGENTS=true
    TARGET_CODEX=true
  fi
}
parse_args "$@"

# ── Helpers ───────────────────────────────────────────────────────────────────

GREEN='\033[0;32m'
YELLOW='\033[1;33m'
CYAN='\033[0;36m'
RESET='\033[0m'

installed=0
skipped=0
errors=0

install_skill_dir() {
  local src_skill_dir="$1"   # e.g. .../skills/flexi-explore
  local dst_base="$2"        # e.g. ~/.config/opencode/skills
  local name
  name="$(basename "$src_skill_dir")"
  local src="$src_skill_dir/SKILL.md"
  local dst_dir="$dst_base/$name"
  local dst="$dst_dir/SKILL.md"

  if [[ ! -f "$src" ]]; then
    return
  fi

  if [[ "$DRY_RUN" == "true" ]]; then
    echo -e "  ${CYAN}[dry-run]${RESET} would install: $dst"
    return
  fi

  mkdir -p "$dst_dir"
  if cp "$src" "$dst"; then
    echo -e "  ${GREEN}✓${RESET} $dst"
    (( installed++ )) || true
  else
    echo -e "  ${YELLOW}✗${RESET} failed: $dst" >&2
    (( errors++ )) || true
  fi
}

install_all_to() {
  local dst_base="$1"
  local label="$2"
  echo "→ $label ($dst_base)"
  for skill_dir in "$SKILLS_DIR"/*/; do
    [[ -d "$skill_dir" ]] || continue
    install_skill_dir "$skill_dir" "$dst_base"
  done
}

# ── Install ───────────────────────────────────────────────────────────────────

echo ""
echo "FlexiBee MCP — skill installer"
echo "Skills source: $SKILLS_DIR"
echo ""

skill_count="$(find "$SKILLS_DIR" -maxdepth 2 -name "SKILL.md" | wc -l)"
echo "Found $skill_count skills:"
for skill_dir in "$SKILLS_DIR"/*/; do
  [[ -d "$skill_dir" ]] && echo "  - $(basename "$skill_dir")"
done
echo ""

if [[ "$TARGET_OPENCODE" == "true" ]]; then
  install_all_to "$HOME/.config/opencode/skills" "OpenCode (global)"
  echo ""
fi

if [[ "$TARGET_CLAUDE" == "true" ]]; then
  install_all_to "$HOME/.claude/skills" "Claude Code (global)"
  echo ""
fi

if [[ "$TARGET_AGENTS" == "true" ]]; then
  install_all_to "$HOME/.agents/skills" "Agent Skills (global — OpenCode, Claude Code, Antigravity, …)"
  echo ""
fi

if [[ "$TARGET_CODEX" == "true" ]]; then
  CODEX_AGENTS="$HOME/.codex/AGENTS.md"
  echo "→ Codex CLI AGENTS.md ($CODEX_AGENTS)"
  if [[ "$DRY_RUN" == "true" ]]; then
    echo -e "  ${CYAN}[dry-run]${RESET} would write/update: $CODEX_AGENTS"
  else
    mkdir -p "$HOME/.codex"
    # Write a header if the file doesn't exist yet.
    if [[ ! -f "$CODEX_AGENTS" ]]; then
      cat > "$CODEX_AGENTS" << 'HDR'
# FlexiBee MCP — Agent Instructions
#
# This file was generated by scripts/install-skills.sh from the
# flexibee-mcp repository. Re-run the script to update.

HDR
    fi

    # Append each skill's content only if not already present.
    for skill_dir in "$SKILLS_DIR"/*/; do
      [[ -d "$skill_dir" ]] || continue
      skill_name="$(basename "$skill_dir")"
      src="$skill_dir/SKILL.md"
      [[ -f "$src" ]] || continue

      marker="<!-- skill:$skill_name -->"
      if grep -q "$marker" "$CODEX_AGENTS" 2>/dev/null; then
        echo -e "  ${YELLOW}↷${RESET} already present: $skill_name (skipped)"
        (( skipped++ )) || true
      else
        {
          echo ""
          echo "$marker"
          cat "$src"
          echo "<!-- /skill:$skill_name -->"
        } >> "$CODEX_AGENTS"
        echo -e "  ${GREEN}✓${RESET} appended: $skill_name"
        (( installed++ )) || true
      fi
    done
  fi
  echo ""
fi

# ── Summary ───────────────────────────────────────────────────────────────────

if [[ "$DRY_RUN" == "true" ]]; then
  echo "Dry-run complete. No files were written."
else
  echo "Done."
  echo "  Installed : $installed"
  [[ $skipped -gt 0 ]] && echo "  Skipped   : $skipped"
  [[ $errors  -gt 0 ]] && echo "  Errors    : $errors" >&2
fi

echo ""
echo "Next steps:"
echo "  1. Restart your AI client to pick up new skills."
echo "  2. For OpenCode: type /mcp in the TUI to verify the MCP server."
echo "  3. For Claude Code: run 'claude mcp list' to check the MCP server."
echo "  4. Ask your assistant: \"What FlexiBee skills are available?\""
echo ""
